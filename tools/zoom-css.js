/* Makes the "computer" copies of the stylesheets: every px size × 0.75, so on screens 900px and wider
   the site looks the way it does with the browser zoomed out to 75% (owner's request, 2026-10-12).
   vw/vh sizes are left alone, exactly as browser zoom does. Phones keep the normal stylesheets.
   Runs automatically from build-pages.js; run it by hand after any CSS change: node tools/zoom-css.js */
const fs = require('fs');
const Z = 0.75;
const scale = css => css.replace(/(-?\d*\.?\d+)px/g, (m, n) => {
  const v = parseFloat(n);
  if (Math.abs(v) <= 1) return m;   // hairlines stay 1px
  return +(v * Z).toFixed(3) + 'px';
});
for (const [src, out] of [['css/style.css', 'css/style-75.css'], ['css/pages.css', 'css/pages-75.css']]) {
  fs.writeFileSync(out, '/* GENERATED by tools/zoom-css.js from ' + src + ' (all px × ' + Z + '). Do not edit: edit ' + src + ' and re-run. */\n' + scale(fs.readFileSync(src, 'utf8')));
}
module.exports = { Z };
